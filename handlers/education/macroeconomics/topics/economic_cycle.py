from telegram import Update
from telegram.ext import ContextTypes


async def economic_cycle(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
):

    text = """
🔄 چرخه اقتصادی (Economic Cycle)

چرخه اقتصادی به روند طبیعی تغییرات فعالیت‌های اقتصادی در طول زمان گفته می‌شود. اقتصاد کشورها معمولاً به صورت مداوم بین دوره‌های رشد، رونق، رکود و بهبود در حرکت است و این تغییرات به عنوان چرخه اقتصادی شناخته می‌شوند.

یک چرخه اقتصادی معمولاً از چهار مرحله تشکیل می‌شود:
• رونق (Expansion)
• اوج (Peak)
• رکود (Recession)
• بهبود (Recovery)

شناخت موقعیت اقتصاد در این چرخه به سرمایه‌گذاران، شرکت‌ها و سیاست‌گذاران کمک می‌کند تا تصمیمات مناسب‌تری در زمینه سرمایه‌گذاری، تولید، مصرف و سیاست‌های پولی و مالی اتخاذ کنند.

🎯 اهمیت:
چرخه اقتصادی یکی از مهم‌ترین مفاهیم اقتصاد کلان است و بر بازار سهام، قیمت طلا، نرخ ارز، نرخ بهره، اشتغال و رشد اقتصادی تأثیر مستقیم دارد.
"""

    await update.message.reply_text(text)