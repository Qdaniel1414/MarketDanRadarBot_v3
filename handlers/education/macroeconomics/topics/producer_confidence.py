from telegram import Update
from telegram.ext import ContextTypes


async def producer_confidence(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
):

    text = """
🏭 شاخص اعتماد تولیدکننده (Producer Confidence)

شاخص اعتماد تولیدکننده یا Producer Confidence میزان خوش‌بینی یا بدبینی مدیران و صاحبان کسب‌وکار نسبت به وضعیت فعلی و آینده اقتصاد را اندازه‌گیری می‌کند. این شاخص بر اساس نظرسنجی از تولیدکنندگان درباره میزان سفارشات، تولید، سرمایه‌گذاری، استخدام نیروی کار و شرایط اقتصادی محاسبه می‌شود.

افزایش اعتماد تولیدکنندگان معمولاً نشان‌دهنده انتظار رشد اقتصادی، افزایش سرمایه‌گذاری و توسعه فعالیت‌های تولیدی است، در حالی که کاهش آن می‌تواند نشانه کاهش تولید، افت سرمایه‌گذاری و کند شدن رشد اقتصاد باشد.

🎯 اهمیت:
شاخص اعتماد تولیدکننده یکی از شاخص‌های پیشرو اقتصاد است و می‌تواند بر بازارهای سهام، ارزش ارز، قیمت کالاها، نرخ بهره و تصمیمات سرمایه‌گذاران و بانک‌های مرکزی تأثیر قابل توجهی داشته باشد.
"""

    await update.message.reply_text(text)