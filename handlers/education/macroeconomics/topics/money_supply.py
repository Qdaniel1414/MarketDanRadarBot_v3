from telegram import Update
from telegram.ext import ContextTypes


async def money_supply(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
):

    text = """
💵 عرضه پول (Money Supply)

عرضه پول یا Money Supply به مجموع پول در گردش و سپرده‌های بانکی موجود در اقتصاد گفته می‌شود. این شاخص نشان می‌دهد چه مقدار پول در اختیار مردم، شرکت‌ها و مؤسسات مالی قرار دارد و یکی از مهم‌ترین معیارهای سنجش وضعیت پولی یک کشور است.

عرضه پول معمولاً در قالب شاخص‌هایی مانند M0، M1، M2 و M3 اندازه‌گیری می‌شود که هر کدام سطوح مختلفی از پول و شبه‌پول را شامل می‌شوند. افزایش بیش از حد عرضه پول، در صورتی که با رشد تولید همراه نباشد، می‌تواند باعث افزایش تورم و کاهش ارزش پول ملی شود.

🎯 اهمیت:
عرضه پول تأثیر مستقیمی بر تورم، نرخ بهره، رشد اقتصادی، ارزش ارز، قیمت طلا، بازار سهام و سایر بازارهای مالی دارد و یکی از مهم‌ترین ابزارهای تحلیل اقتصاد کلان محسوب می‌شود.
"""

    await update.message.reply_text(text)