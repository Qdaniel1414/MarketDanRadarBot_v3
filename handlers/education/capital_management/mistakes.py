from telegram import Update
from telegram.ext import ContextTypes


async def mistakes_handler(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
):
    if update.message is None:
        return

    text = """
❌ اشتباهات رایج معامله‌گران

━━━━━━━━━━━━━━━━━━

1️⃣ ریسک بیش از حد در یک معامله

بزرگ‌ترین اشتباه معامله‌گران تازه‌کار.

اگر فقط چند معامله اشتباه انجام شود،
ممکن است کل حساب نابود شود.

━━━━━━━━━━━━━━━━━━

2️⃣ نداشتن حد ضرر (Stop Loss)

بدون حد ضرر وارد معامله نشوید.

بازار هیچ تضمینی برای برگشت ندارد.

━━━━━━━━━━━━━━━━━━

3️⃣ جابه‌جا کردن حد ضرر

بعد از ورود،
حد ضرر را عقب نکشید.

این کار معمولاً ضرر را بزرگ‌تر می‌کند.

━━━━━━━━━━━━━━━━━━

4️⃣ انتقام از بازار

بعد از ضرر،
سریع وارد معامله بعدی نشوید.

اجازه دهید احساسات آرام شوند.

━━━━━━━━━━━━━━━━━━

5️⃣ حجم بیش از اندازه

لات بزرگ یعنی استرس بزرگ.

همیشه اندازه پوزیشن را با مدیریت سرمایه محاسبه کنید.

━━━━━━━━━━━━━━━━━━

6️⃣ معامله بدون برنامه

قبل از ورود باید مشخص باشد:

✅ نقطه ورود
✅ حد ضرر
✅ حد سود
✅ دلیل ورود

━━━━━━━━━━━━━━━━━━

7️⃣ طمع

نباید همیشه دنبال سودهای بزرگ باشید.

سودهای کوچک اما مستمر
در بلندمدت حساب را رشد می‌دهند.

━━━━━━━━━━━━━━━━━━

8️⃣ ترس

ترس باعث می‌شود:

❌ زود از معامله خارج شوید
❌ فرصت‌های خوب را از دست بدهید.

━━━━━━━━━━━━━━━━━━

9️⃣ نداشتن ژورنال معاملاتی

تمام معاملات خود را ثبت کنید.

این کار باعث پیشرفت سریع‌تر می‌شود.

━━━━━━━━━━━━━━━━━━

🎯 قانون طلایی

🔒 اول سرمایه را حفظ کنید.

💰 سود همیشه بعد از حفظ سرمایه می‌آید.

معامله‌گر حرفه‌ای
اول به فکر زنده ماندن در بازار است،
بعد به فکر سود.
"""

    await update.message.reply_text(text)