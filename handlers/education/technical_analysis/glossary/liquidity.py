        "📌 اگر خریدار و فروشنده زیاد باشد:\n"
        "✅ نقدشوندگی بالا است.\n\n"

        "📌 اگر خریدار و فروشنده کم باشد:\n"
        "❌ نقدشوندگی پایین است.\n\n"

        "نمونه بازارهای با نقدشوندگی بالا:\n\n"

        "💵 فارکس\n"
        "🥇 طلا\n"
        "₿ بیت‌کوین\n"
        "📈 شاخص S&P500\n\n"

