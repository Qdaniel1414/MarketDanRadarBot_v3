from telegram import Update
from telegram.ext import ContextTypes


async def risk_reward_intro(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
):
    if update.message is None:
        return

    text = (
        "🎯 ریسک به ریوارد (Risk / Reward)\n\n"

        "ریسک به ریوارد یعنی مقایسه مقدار ضرر احتمالی "
        "با سود احتمالی یک معامله.\n\n"

        "📌 فرمول:\n\n"

        "نسبت ریسک به ریوارد = سود احتمالی ÷ زیان احتمالی\n\n"

        "مثال:\n\n"

        "💵 ورود: 100\n"
        "🛑 حد ضرر: 95\n"
        "🎯 هدف: 110\n\n"

        "ریسک = 100 − 95 = 5\n"
        "ریوارد = 110 − 100 = 10\n\n"

        "نسبت ریسک به ریوارد:\n"
        "10 ÷ 5 = 2\n\n"

        "📊 نسبت نهایی: 1 : 2\n\n"

        "یعنی به ازای پذیرش 1 واحد ریسک، "
        "هدف معامله 2 واحد سود است.\n\n"

        "نسبت‌های رایج:\n\n"

        "🔴 1 : 1\n"
        "🟡 1 : 1.5\n"
        "🟢 1 : 2\n"
        "🟢 1 : 3\n\n"

        "❌ اشتباه رایج:\n"
        "ورود به معامله بدون تعیین حد ضرر و حد سود.\n\n"

        "🎯 نکته مهم:\n"
        "ریسک به ریوارد به‌تنهایی تضمین‌کننده سودآوری نیست؛ "
        "احتمال موفقیت معامله، هزینه‌ها و مدیریت سرمایه هم اهمیت دارند."
    )

    await update.message.reply_text(text)